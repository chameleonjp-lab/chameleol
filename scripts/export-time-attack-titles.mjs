// Usage: node scripts/export-time-attack-titles.mjs --revision <verified game commit>
import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { LANGUAGE_IDS } from '../src/i18n/languages.js';
import { MESSAGES } from '../src/i18n/messages/index.js';
import { TIME_ATTACK_TITLES } from '../src/rules/time-attack/v1/index.js';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const SOURCES = [
  'src/i18n/languages.js',
  'src/i18n/messages/index.js',
  'src/i18n/messages/time-attack.js',
  'src/i18n/messages/time-attack-titles.js',
  'src/rules/time-attack/v1',
];

function verifyRevision(revision) {
  if (!/^[0-9a-f]{40}$/.test(revision ?? '')) {
    throw new Error('Provide the full game source commit with --revision.');
  }
  const verified = execFileSync('git', ['rev-parse', '--verify', `${revision}^{commit}`], {
    cwd: ROOT,
    encoding: 'utf8',
  }).trim();
  const difference = spawnSync('git', ['diff', '--quiet', verified, '--', ...SOURCES], { cwd: ROOT });
  const untracked = execFileSync('git', ['ls-files', '--others', '--exclude-standard', '--', ...SOURCES], {
    cwd: ROOT,
    encoding: 'utf8',
  }).trim();
  if (difference.status !== 0 || untracked) throw new Error('The title source differs from the requested commit.');
  return verified;
}

export function createTimeAttackTitleExport(sourceCommit) {
  const titles = TIME_ATTACK_TITLES.map(({ id, minCs, maxCs }) => {
    const labels = Object.fromEntries(LANGUAGE_IDS.map(lang => {
      const label = MESSAGES[lang][id];
      if (!label) throw new Error(`Missing ${lang} title: ${id}`);
      return [lang, label];
    }));
    return { id, minCs, maxCs, labels };
  });
  const contentSha256 = createHash('sha256').update(JSON.stringify(titles)).digest('hex');
  return { sourceCommit, contentSha256, titles };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv[2] !== '--revision' || process.argv.length !== 4) {
    throw new Error('Usage: node scripts/export-time-attack-titles.mjs --revision <verified game commit>');
  }
  const { sourceCommit, contentSha256, titles } = createTimeAttackTitleExport(verifyRevision(process.argv[3]));
  process.stdout.write([
    '// Generated by chameleol/scripts/export-time-attack-titles.mjs.',
    `export const sourceCommit = ${JSON.stringify(sourceCommit)};`,
    `export const contentSha256 = ${JSON.stringify(contentSha256)};`,
    `export const titles = Object.freeze(${JSON.stringify(titles, null, 2)}.map(row => Object.freeze({ ...row, labels: Object.freeze(row.labels) })));`,
    'export const timeAttackTitleData = Object.freeze({ sourceCommit, contentSha256, titles });',
    '',
  ].join('\n'));
}
